  slot smallint primary key check (slot in (1,2)),
  user_id uuid not null unique references auth.users(id)
);
create function public.ob_is_admin() returns boolean language sql stable security definer
set search_path = '' as $$ select exists(select 1 from private.admins where user_id=auth.uid()) $$;

create table public.ob_profiles (
  id uuid primary key references auth.users(id),
  username text not null default '' check (length(username)<=80),
  points integer not null default 0 check(points>=0),
  best integer not null default 0,
  best_score integer not null default 0,
  created_at timestamptz not null default now()
);
create function private.new_customer() returns trigger language plpgsql security definer set search_path='' as $$
begin
  insert into public.ob_profiles(id,username) values(new.id,left(coalesce(new.raw_user_meta_data->>'username',''),80));
  return new;
end $$;
